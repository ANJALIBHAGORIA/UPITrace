"""Implementations of the nine agent tools (spec section 6), backed by the
in-memory store. Every connector here is SIMULATED — there is no live
payment/bank/merchant integration in this codebase yet, and each output
schema says so explicitly via `source_mode`.

`propose_resolution` here is a deterministic stand-in (reconciliation ->
recommended action), not an AI-authored proposal. The Gemini-grounded version
described in spec section 8 belongs to Phase 3; this keeps the
`/actions/propose` API route functional in the meantime and is clearly
labelled as non-AI via ActionProposal.rationale.
"""
from __future__ import annotations

from datetime import datetime, timezone
from itertools import count
from typing import Optional

from src.main.backend.models import (
    ActionExecution,
    ActionProposal,
    ActionStatus,
    ExecutionMode,
    ExecutionStatus,
    OutcomeVerificationResult,
)
from src.main.backend.reconciliation import ReconciliationResult
from src.main.backend.store import InMemoryStore

from . import schemas as s

_action_counter = count(1)
_execution_counter = count(1)


def find_payment_attempt(store: InMemoryStore, inp: s.FindPaymentAttemptInput) -> s.FindPaymentAttemptOutput:
    candidates = []
    reasons = []
    for pa in store.payment_attempts.values():
        if inp.payment_attempt_id and pa.payment_attempt_id == inp.payment_attempt_id:
            candidates.append(pa)
            reasons.append("exact payment_attempt_id match")
        elif inp.transaction_ref and pa.transaction_ref == inp.transaction_ref:
            candidates.append(pa)
            reasons.append("exact transaction_ref match")
        elif inp.merchant_order_ref and pa.merchant_order_ref == inp.merchant_order_ref:
            candidates.append(pa)
            reasons.append("merchant_order_ref match")
    return s.FindPaymentAttemptOutput(candidates=candidates, match_reasons=reasons, ambiguous=len(candidates) > 1)


def fetch_payment_status(store: InMemoryStore, inp: s.FetchPaymentStatusInput) -> s.FetchPaymentStatusOutput:
    pa = store.payment_attempts.get(inp.payment_attempt_id)
    if pa is None:
        return s.FetchPaymentStatusOutput(found=False)
    return s.FetchPaymentStatusOutput(
        found=True, provider_status=pa.provider_status,
        source_timestamp=pa.created_at.isoformat(), source_system=pa.source_system,
    )


def fetch_merchant_order(store: InMemoryStore, inp: s.FetchMerchantOrderInput) -> s.FetchMerchantOrderOutput:
    order = store.merchant_order_for(transaction_ref=inp.transaction_ref)
    if order is None and inp.order_ref:
        order = store.merchant_orders.get(inp.order_ref)
    if order is None or order.merchant_id != inp.merchant_id:
        return s.FetchMerchantOrderOutput(found=False)
    return s.FetchMerchantOrderOutput(found=True, order=order)


def inspect_notification_records(
    store: InMemoryStore, inp: s.InspectNotificationRecordsInput
) -> s.InspectNotificationRecordsOutput:
    return s.InspectNotificationRecordsOutput(
        notifications=store.notifications_for_payment_attempt(inp.payment_attempt_id)
    )


def retrieve_bank_evidence(store: InMemoryStore, inp: s.RetrieveBankEvidenceInput) -> s.RetrieveBankEvidenceOutput:
    records = [
        e for e in store.evidence_for_incident(inp.incident_id)
        if e.evidence_type == "BANK_RECORD"
    ]
    return s.RetrieveBankEvidenceOutput(records=records)


def retrieve_runbook(store: InMemoryStore, inp: s.RetrieveRunbookInput) -> s.RetrieveRunbookOutput:
    matches = store.runbooks_matching([inp.classification], inp.query)
    rationale = (
        f"Matched by scenario tag '{inp.classification}'"
        + (f" and query '{inp.query}'" if inp.query else "")
    )
    return s.RetrieveRunbookOutput(runbooks=matches, retrieval_rationale=rationale)


def propose_resolution(
    store: InMemoryStore, incident_id: str, reconciliation: ReconciliationResult
) -> ActionProposal:
    """Deterministic stand-in for Phase 3's Gemini-grounded proposal. The
    recommended action is read directly off the reconciliation result, not
    generated by a model."""
    action_type_by_classification = {
        "CONFIRMED": "NO_ACTION_REQUIRED",
        "PENDING": "SCHEDULE_RECHECK",
        "STATUS_MISMATCH": "FETCH_LATEST_STATUS",
        "MERCHANT_CONFIRMATION_MISSING": "RECHECK_MERCHANT_ORDER",
        "INSUFFICIENT_EVIDENCE": "REQUEST_ADDITIONAL_EVIDENCE",
        "POSSIBLE_DUPLICATE": "CONFIRM_SINGLE_SETTLEMENT",
        "REVERSAL_UNVERIFIED": "QUERY_REVERSAL_STATUS",
        "UNRESOLVED": "ESCALATE_FOR_MANUAL_REVIEW",
    }
    classification_value = reconciliation.classification.value
    action_type = action_type_by_classification.get(classification_value, "ESCALATE_FOR_MANUAL_REVIEW")
    proposal = ActionProposal(
        action_id=f"ACT-{next(_action_counter):06d}",
        incident_id=incident_id,
        action_type=action_type,
        description=f"Deterministic recommendation for classification={classification_value}",
        rationale=(
            "Derived directly from reconciliation.permitted_checks "
            f"{reconciliation.permitted_checks} — not an AI-authored proposal (Phase 2)."
        ),
        evidence_ids=reconciliation.evidence_ids,
        requires_human_approval=True,
        proposed_at=datetime.now(timezone.utc),
        status=ActionStatus.PROPOSED,
    )
    store.action_proposals[proposal.action_id] = proposal
    return proposal


def request_action(store: InMemoryStore, inp: s.RequestActionInput) -> s.RequestActionOutput:
    proposal = store.action_proposals.get(inp.action_id)
    if proposal is None:
        return s.RequestActionOutput(approved=False, reason="unknown action_id")

    # Idempotency is checked before the status gate: replaying a key that
    # already executed must return that prior execution, even though the
    # proposal's status has since moved past PROPOSED/APPROVED.
    for execution in store.action_executions.values():
        if execution.idempotency_key == inp.idempotency_key:
            return s.RequestActionOutput(
                approved=True, execution_id=execution.execution_id,
                execution_status=execution.execution_status.value, reason="idempotent replay",
            )

    if proposal.status not in (ActionStatus.PROPOSED, ActionStatus.APPROVED):
        return s.RequestActionOutput(approved=False, reason=f"action is {proposal.status.value}, not actionable")

    proposal.status = ActionStatus.APPROVED
    execution = ActionExecution(
        execution_id=f"EXE-{next(_execution_counter):06d}",
        action_id=proposal.action_id,
        idempotency_key=inp.idempotency_key,
        execution_mode=ExecutionMode.SIMULATED,
        execution_status=ExecutionStatus.SUCCEEDED,
        executed_at=datetime.now(timezone.utc),
        result={"simulated": True, "action_type": proposal.action_type},
    )
    store.action_executions[execution.execution_id] = execution
    proposal.status = ActionStatus.EXECUTED
    return s.RequestActionOutput(
        approved=True, execution_id=execution.execution_id,
        execution_status=execution.execution_status.value, reason="executed (simulated)",
    )


def verify_outcome(store: InMemoryStore, inp: s.VerifyOutcomeInput) -> s.VerifyOutcomeOutput:
    execution = store.action_executions.get(inp.execution_id)
    if execution is None:
        return s.VerifyOutcomeOutput(result=OutcomeVerificationResult.UNKNOWN)
    actual = (execution.result or {}).get("action_type")
    if actual is None:
        return s.VerifyOutcomeOutput(result=OutcomeVerificationResult.UNKNOWN)
    matched = actual == inp.expected_result
    return s.VerifyOutcomeOutput(
        result=OutcomeVerificationResult.VERIFIED if matched else OutcomeVerificationResult.NOT_VERIFIED,
    )
